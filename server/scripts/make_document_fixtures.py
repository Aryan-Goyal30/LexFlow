"""Write the fictional extraction fixtures to server/tests/fixtures/documents/.

    python scripts/make_document_fixtures.py

The files are generated by ``tests/document_fixtures.py`` (deterministic) and
committed so the end-to-end tests can upload them; ``tests/test_extractors.py``
checks that the committed copies still match the builder.
"""

from __future__ import annotations

import sys
from pathlib import Path

SERVER_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(SERVER_ROOT))

from tests.document_fixtures import FIXTURE_DIR, FIXTURE_FILES  # noqa: E402


def main() -> int:
    FIXTURE_DIR.mkdir(parents=True, exist_ok=True)
    for name, build in FIXTURE_FILES.items():
        (FIXTURE_DIR / name).write_bytes(build())
        print(f"wrote {name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
