class Failing:
    name, model = "scripted", "scripted-assessment-v1"

    def __init__(self, error: Exception | None = None, text: str | None = None) -> None:
        self.error, self.text, self.calls = error, text, 0

    def generate(self, request: AssessmentRequest) -> Response:
        self.calls += 1
        if self.error is not None:
            raise self.error
        return Response(text=self.text or "")


def test_a_provider_failure_is_stored_safely_and_a_new_attempt_recovers(
    as_: As, db: Session, run: AnalysisRun, monkeypatch: pytest.MonkeyPatch
) -> None:
    lead = as_("lead")
    accept(lead, run, "F1", "P1")
    timeout = ProviderError("provider-timeout", "The provider did not answer in time.", retry=True)
    monkeypatch.setattr(provider_mod, "provider_for", lambda settings: Failing(timeout))
    failed = generate(lead, run)
    assert (failed["status"], failed["reasonCode"], failed["result"]) == (
        "failed",
        "provider-timeout",
        None,
    )
    assert review(lead, run, failed, "accepted").status_code == 409
    (event,) = events(db, "assessment.failed")
    assert event.details["reason"] == "provider-timeout" and event.outcome == "failed"

    crash = Failing(RuntimeError("SYNTHETIC bug with the prompt text inside"))
    monkeypatch.setattr(provider_mod, "provider_for", lambda settings: crash)
    bug = generate(lead, run)
    assert (bug["status"], bug["reasonCode"]) == ("failed", "provider-error")
    assert "SYNTHETIC bug" not in json.dumps(bug)

    garbled = Failing(text="not json at all")
    monkeypatch.setattr(provider_mod, "provider_for", lambda settings: garbled)
    unreadable = generate(lead, run)
    assert (unreadable["status"], unreadable["reasonCode"]) == ("failed", "invalid-output")
    assert garbled.calls == 2  # one more try, then failed

    monkeypatch.setattr(provider_mod, "provider_for", lambda settings: Recording())
    recovered = generate(lead, run)
    assert recovered["status"] == "ready"
    listing = lead.get(url(run)).json()
    assert [i["status"] for i in listing["items"]] == ["ready", "failed", "failed", "failed"]


def test_a_misleading_summary_withholds_the_whole_assessment(
    as_: As, run: AnalysisRun, monkeypatch: pytest.MonkeyPatch
) -> None:
    lead = as_("lead")
