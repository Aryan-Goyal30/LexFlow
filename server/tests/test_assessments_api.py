class Recording:
    """The scripted double, keeping each request it was given."""

    name, model = "scripted", "scripted-assessment-v1"

    def __init__(self) -> None:
        self.requests: list[AssessmentRequest] = []

    def generate(self, request: AssessmentRequest) -> Response:
        self.requests.append(request)
        return ScriptedAssessmentProvider().generate(request)


def test_only_accepted_findings_reach_the_provider_never_notes_or_excluded_ones(
    as_: As, run: AnalysisRun, monkeypatch: pytest.MonkeyPatch
) -> None:
    recording = Recording()
    monkeypatch.setattr(provider_mod, "provider_for", lambda settings: recording)
    lead = as_("lead")
    stored = run.result or {}
    decide(lead, run, "F1", "accepted", note=NOTE)
    decide(lead, run, "F2", "rejected", note=NOTE)
    decide(lead, run, "C1", "edited", reviewedText=WORDING, note=NOTE)
    accept(lead, run, "P1")
    # I1 and P2 stay unreviewed.
    body = generate(lead, run)
    assert body["status"] == "ready"
    assert body["excluded"] == {"rejected": 1, "unreviewed": 2}
    (request,) = recording.requests
    sent = request.prompt
    assert NOTE not in sent
    assert stored["facts"][0]["statement"] in sent  # F1 accepted
    assert stored["facts"][1]["statement"] not in sent  # F2 rejected
    assert stored["issues"][0]["question"] not in sent  # I1 unreviewed
    assert WORDING in sent and stored["contradictions"][0]["description"] not in sent
    assert "P2" not in sent  # unreviewed precedent
    assert [p.id for p in request.inputs.precedents] == ["P1"]


