def test_review_keeps_the_original_and_follows_the_phase6_rules(
    as_: As, db: Session, run: AnalysisRun, ready: dict[str, Any]
) -> None:
    lead = as_("lead")
    original = db.get(OutcomeAssessment, uuid.UUID(ready["id"]))
    assert original is not None
    before = json.dumps(original.result, sort_keys=True)

    accepted = review(lead, run, ready, "accepted")
    assert accepted.status_code == 200 and accepted.json()["version"] == 1
    again = review(lead, run, ready, "accepted")  # a retry from an old copy
    assert (again.status_code, again.json()["code"]) == (409, "review-changed")
    same = review(lead, run, ready, "accepted", version=1)  # changes nothing
    assert same.status_code == 200 and same.json()["version"] == 1

    missing = review(lead, run, ready, "edited", version=1)
    assert (missing.status_code, missing.json()["code"]) == (422, "reviewed-text-required")
    unchanged = review(
        lead, run, ready, "edited", version=1, reviewedText=ready["result"]["summary"]
    )
    assert (unchanged.status_code, unchanged.json()["code"]) == (422, "wording-unchanged")
    stray = review(lead, run, ready, "accepted", version=1, reviewedText="x")
    assert (stray.status_code, stray.json()["code"]) == (422, "reviewed-text-not-allowed")

    edited = review(lead, run, ready, "edited", version=1, reviewedText=WORDING, note=NOTE)
    assert edited.status_code == 200 and edited.json()["reviewedText"] == WORDING
    rejected = review(lead, run, ready, "rejected", version=2, note=NOTE)
    cleared = review(lead, run, ready, "unreviewed", version=3, note=NOTE)
    assert rejected.status_code == cleared.status_code == 200

    history = lead.get(f"{url(run)}/{ready['id']}/review/history").json()["items"]
    assert [(e["version"], e["status"]) for e in history] == [
        (1, "accepted"),
        (2, "edited"),
        (3, "rejected"),
        (4, "unreviewed"),
    ]
    assert db.scalar(select(func.count()).select_from(OutcomeAssessmentReviewEvent)) == 4
    db.refresh(original)
    assert json.dumps(original.result, sort_keys=True) == before  # never changed


