def url(run: AnalysisRun | uuid.UUID | str, case: Any = SATTVIK) -> str:
    run_id = run.id if isinstance(run, AnalysisRun) else run
    return f"/api/cases/{case}/analysis-runs/{run_id}/assessments"


def decide(http: TestClient, run: AnalysisRun, finding: str, status: str, **extra: Any) -> Any:
    base = f"/api/cases/{SATTVIK}/analysis-runs/{run.id}/reviews"
    version = next(
        i["version"] for i in http.get(base).json()["items"] if i["findingId"] == finding
    )
    response = http.put(
        f"{base}/{finding}", json={"status": status, "expectedVersion": version, **extra}
    )
    assert response.status_code == 200, response.text
    return response


def accept(http: TestClient, run: AnalysisRun, *findings: str) -> None:
    for finding in findings:
        decide(http, run, finding, "accepted")


def generate(http: TestClient, run: AnalysisRun) -> Any:
    response = http.post(url(run))
    assert response.status_code == 201, response.text
    return response.json()


def review(
    http: TestClient, run: AnalysisRun, assessment: dict[str, Any], status: str, **extra: Any
) -> Any:
    return http.put(
        f"{url(run)}/{assessment['id']}/review",
        json={"status": status, "expectedVersion": extra.pop("version", 0), **extra},
    )


def brief_text(http: TestClient, run: AnalysisRun) -> str:
    response = http.get(f"/api/cases/{SATTVIK}/analysis-runs/{run.id}/brief")
    assert response.status_code == 200, response.text
    return "\n".join(p.text for p in docx.Document(io.BytesIO(response.content)).paragraphs)


